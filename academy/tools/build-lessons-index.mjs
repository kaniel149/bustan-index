// academy/tools/build-lessons-index.mjs — regenerate academy/assets/lessons.js from courses/*.html
import fs from 'node:fs'; import path from 'node:path';
const ROOT = path.resolve(new URL('.', import.meta.url).pathname, '..');
const TRACKS = {
  'solar-fundamentals': { order: 1, icon: '☀️', en: 'Solar Fundamentals', he: 'מבוא לסולאר', th: 'พื้นฐานพลังงานแสงอาทิตย์' },
  'technical':          { order: 2, icon: '⚡', en: 'Technical — Installation & Electrical', he: 'טכני — התקנה וחשמל', th: 'เทคนิค — การติดตั้งและไฟฟ้า' },
  'sales-bd':           { order: 3, icon: '💼', en: 'Sales & Business Development', he: 'מכירות ופיתוח עסקי', th: 'การขายและพัฒนาธุรกิจ' },
  'ev-storage':         { order: 4, icon: '🔋', en: 'EV & Energy Storage', he: 'רכב חשמלי ואגירת אנרגיה', th: 'EV และการกักเก็บพลังงาน' },
  'management':         { order: 5, icon: '📊', en: 'Management & Operations', he: 'ניהול ותפעול', th: 'การจัดการและการดำเนินงาน' },
};
const clean = s => s.replace(/<[^>]+>/g, '').replace(/\s+/g, ' ').trim();
function title(html, lang) {
  const a = html.match(new RegExp(`<h1 class="lesson-title" data-${lang}>([^<]*)</h1>`));
  if (a) return clean(a[1]);
  const h1 = html.match(/<h1[^>]*>([\s\S]*?)<\/h1>/); if (!h1) return '';
  const s = h1[1].match(new RegExp(`<span data-${lang}>([\\s\\S]*?)</span>`));
  return s ? clean(s[1]) : '';
}
const lessons = [];
for (const f of fs.readdirSync(path.join(ROOT, 'courses')).filter(f => /^[a-z-]+-\d{2}\.html$/.test(f)).sort()) {
  const m = f.match(/^(.*)-(\d{2})\.html$/); const html = fs.readFileSync(path.join(ROOT, 'courses', f), 'utf8');
  const en = title(html, 'en'), he = title(html, 'he'), th = title(html, 'th');
  if (!en || !he || !th) throw new Error(`${f}: missing title (en=${!!en} he=${!!he} th=${!!th})`);
  lessons.push({ slug: f.replace('.html', ''), track: m[1], num: Number(m[2]), file: `courses/${f}`, title: { en, he, th } });
}
lessons.sort((a, b) => TRACKS[a.track].order - TRACKS[b.track].order || a.num - b.num);
const out = `// GENERATED by tools/build-lessons-index.mjs — do not edit by hand\nwindow.ACADEMY_TRACKS = ${JSON.stringify(TRACKS, null, 2)};\nwindow.ACADEMY_LESSONS = ${JSON.stringify(lessons, null, 2)};\n`;
fs.writeFileSync(path.join(ROOT, 'assets', 'lessons.js'), out);
console.log(`wrote assets/lessons.js — ${lessons.length} lessons`);
